--   1. Jalankan aplikasi sekali supaya tabelnya terbentuk, lalu tutup.
--      Perintah di bawah gagal kalau tabelnya belum ada.
--   2. Isikan berkas ini ke database:
--        java -cp lib/h2-2.1.214.jar org.h2.tools.RunScript \
--          -url "jdbc:h2:~/kaspe/db_kaspe;MODE=MySQL;DATABASE_TO_LOWER=TRUE" \
--          -user sa -password "" -script docs/data-contoh.sql
--   3. Buka aplikasi lagi - 64 pengiriman itu sudah ada.
--
-- Semua angka mengikuti rumus aplikasi:
--   berat_bersih = FLOOR(bobot_pabrik x (1 - refraksi/100) / 5) x 5
